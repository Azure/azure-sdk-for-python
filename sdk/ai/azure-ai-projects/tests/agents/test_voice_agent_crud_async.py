from test_base import TestBase, servicePreparer
from devtools_testutils.aio import recorded_by_proxy_async
from devtools_testutils import RecordedTransport
from azure.ai.projects.models import (
    AgentDetails,
    AgentVersionDetails,
    VoiceAgentDefinition,
    VoiceAudioConfig,
    VoiceAudioOutputConfig,
    VoiceOutputModality,
)


class TestVoiceAgentCrudAsync(TestBase):
    """
    Recorded tests covering the voice-agent (`kind="voice"`) REST API surface exposed through
    `project_client.agents.*`.

    NOTE: Some voice-agent REST APIs are intentionally NOT covered here because they are
    currently blocked by known service-side bugs (see this package's engineering notes):
      - `agents.generate_agent(kind="voice")` - returns a `400 invalid_payload` error from the
        service even though the SDK sends the TypeSpec-documented-correct payload.
      - Reading back a conversation (`project_client.agent_endpoint_conversations.*`) using a
        `conversation_id` produced by a live realtime WebSocket session - the service's REST
        conversation-ID validator rejects the ID format generated by the realtime WS subsystem.
        This is also not practical to cover with HTTP-only recorded tests since it requires an
        actual WebSocket session.
    Once these are fixed service-side, tests can be added for them.
    """

    # To run only this test:
    # pytest tests\agents\test_voice_agent_crud_async.py::TestVoiceAgentCrudAsync::test_voice_agent_crud_async -s
    @servicePreparer()
    @recorded_by_proxy_async()
    async def test_voice_agent_crud_async(self, **kwargs):
        """
        Test CRUD operations for voice Agents (`kind="voice"`).

        This test creates a voice agent, creates a new version of it, gets it, gets a specific
        version, lists its versions, and deletes it.

        Routes used in this test:

        Action REST API Route                                Client Method
        ------+---------------------------------------------+-----------------------------------
        POST   /agents/{agent_name}/versions                 project_client.agents.create_version()
        GET    /agents/{agent_name}                          project_client.agents.get()
        GET    /agents/{agent_name}/versions/{agent_version} project_client.agents.get_version()
        GET    /agents/{agent_name}/versions                 project_client.agents.list_versions()
        DELETE /agents/{agent_name}                          project_client.agents.delete()
        """
        print("\n")
        model = kwargs.get("foundry_voice_model_name")
        assert model is not None
        # Voice-agent operations require the preview opt-in.
        project_client = self.create_async_client(operation_group="agents", allow_preview=True, **kwargs)
        agent_name = "MyVoiceAgentCrudTestAsync"

        def make_definition(instructions: str) -> VoiceAgentDefinition:
            return VoiceAgentDefinition(
                model_type="managed",
                model=model,
                instructions=instructions,
                audio=VoiceAudioConfig(
                    output=VoiceAudioOutputConfig(voice="en-US-AvaNeural", voice_type="azure-standard")
                ),
                output_modalities=[VoiceOutputModality.AUDIO],
            )

        async with project_client:
            # Create the initial voice agent (version 1).
            agent_version1: AgentVersionDetails = await project_client.agents.create_version(
                agent_name=agent_name,
                definition=make_definition("You are a helpful voice assistant."),
            )
            self._validate_agent_version(agent_version1, expected_name=agent_name)
            assert agent_version1.definition.kind == "voice"  # type: ignore[attr-defined]

            # Create a new version with updated instructions.
            agent_version2: AgentVersionDetails = await project_client.agents.create_version(
                agent_name=agent_name,
                definition=make_definition("You are a helpful voice assistant. Always greet the caller by name."),
            )
            self._validate_agent_version(agent_version2, expected_name=agent_name)

            # Get the voice agent.
            retrieved_agent: AgentDetails = await project_client.agents.get(agent_name=agent_name)
            self._validate_agent(
                retrieved_agent, expected_name=agent_name, expected_latest_version=agent_version2.version
            )

            # Retrieve a specific version.
            retrieved_agent_version: AgentVersionDetails = await project_client.agents.get_version(
                agent_name=agent_name, agent_version=agent_version1.version
            )
            self._validate_agent_version(
                retrieved_agent_version, expected_name=agent_name, expected_version=agent_version1.version
            )

            # List all versions.
            item_count = 0
            async for listed_agent_version in project_client.agents.list_versions(agent_name=agent_name):
                item_count += 1
                self._validate_agent_version(listed_agent_version, expected_name=agent_name)
            assert item_count >= 2

            # Delete the voice agent.
            result = await project_client.agents.delete(agent_name=agent_name)
            assert result.deleted

    # To run only this test:
    # pytest tests\agents\test_voice_agent_crud_async.py::TestVoiceAgentCrudAsync::test_voice_agent_disable_enable_async -s
    @servicePreparer()
    @recorded_by_proxy_async(RecordedTransport.AZURE_CORE, RecordedTransport.HTTPX)
    async def test_voice_agent_disable_enable_async(self, **kwargs):
        """
        Test disable and enable operations for a voice Agent.

        Routes used in this test:

        Action REST API Route                                Client Method
        ------+---------------------------------------------+-----------------------------------
        POST   /agents/{agent_name}/versions                 project_client.agents.create_version()
        POST   /agents/{agent_name}:disable                  project_client.agents.disable()
        POST   /agents/{agent_name}:enable                   project_client.agents.enable()
        DELETE /agents/{agent_name}                          project_client.agents.delete()
        """
        print("\n")
        model = kwargs.get("foundry_voice_model_name")
        assert model is not None
        project_client = self.create_async_client(operation_group="agents", allow_preview=True, **kwargs)
        agent_name = "VoiceAgentDisableEnableTestAsync"

        async with project_client:
            # Delete any existing agent from previous test runs (ignore failures)
            try:
                await project_client.agents.delete(agent_name=agent_name)
            except Exception:  # pylint: disable=broad-except
                pass

            agent_version: AgentVersionDetails = await project_client.agents.create_version(
                agent_name=agent_name,
                definition=VoiceAgentDefinition(
                    model_type="managed",
                    model=model,
                    instructions="You are a helpful voice assistant.",
                    audio=VoiceAudioConfig(
                        output=VoiceAudioOutputConfig(voice="en-US-AvaNeural", voice_type="azure-standard")
                    ),
                    output_modalities=[VoiceOutputModality.AUDIO],
                ),
            )
            self._validate_agent_version(agent_version, expected_name=agent_name)

            # Disable the agent.
            await project_client.agents.disable(agent_name=agent_name)
            disabled_agent: AgentDetails = await project_client.agents.get(agent_name=agent_name)
            assert str(disabled_agent.state) == "AgentState.DISABLED" or disabled_agent.state == "disabled"

            # Enable the agent.
            await project_client.agents.enable(agent_name=agent_name)
            enabled_agent: AgentDetails = await project_client.agents.get(agent_name=agent_name)
            assert str(enabled_agent.state) == "AgentState.ENABLED" or enabled_agent.state == "enabled"

            # Delete the voice agent.
            result = await project_client.agents.delete(agent_name=agent_name)
            assert result.deleted
