from test_base import TestBase, servicePreparer
from devtools_testutils import recorded_by_proxy
import pytest
from azure.core import MatchConditions
from azure.core.exceptions import HttpResponseError, ResourceNotFoundError
from azure.ai.projects.models import (
    AgentVersionDetails,
    PSTNTelephonyTransferDestination,
    TelephonyBindingStatus,
    TelephonyTransferTarget,
    TelephonyTransferTargets,
    UpdateTelephonyBindingRequest,
    VoiceAgentAudioConfig,
    VoiceAgentAudioOutputConfig,
    VoiceAgentDefinition,
    VoiceOutputModality,
)


class TestVoiceAgentTelephony(TestBase):
    """
    Recorded tests covering the voice-agent telephony REST API surface exposed through
    `project_client.agents.*` (telephony bindings, calls, and transfer targets), and the
    top-level `project_client.agent_endpoint_conversations.*` generated-audio reads.

    NOTE: All tests in this file are currently marked `skip`:
      - The telephony routes (`/agents/{agent_name}/telephony_bindings`, `/telephony_calls`,
        `/telephony_transfer_targets`) are defined in the TypeSpec/SDK but not yet deployed to
        the live test resource: every call returns an empty-body 404 (a routing-layer "no such
        route" response from the service mesh, not an application-level not-found error -
        confirmed by comparing against a known-working route's fully-populated JSON error body).
        Un-skip `test_telephony_bindings_and_transfer_targets`/`test_telephony_calls_not_found`
        once the service deploys these routes.
      - `agent_endpoint_conversations.get_agent_conversation_item_generated_audio*` with a
        made-up conversation/item ID hits the service's conversation-ID format validator and
        returns an unhandled `500 server_error` instead of a clean `404` - the exact same
        pre-existing behavior as the already-documented `beta.agent_endpoint_conversations`
        limitation below. Testing the success path needs a live realtime session whose playback
        was interrupted; testing the not-found path needs a validly-formatted but nonexistent ID
        (the format isn't publicly documented). `test_generated_audio_not_found` is left in as a
        placeholder and currently skipped.

    Further NOTE: the following are intentionally NOT covered here at all since they require real
    infrastructure this test environment does not have:
      - `create_telephony_binding` with a real Teams Phone Extension or Twilio provider account
        (needs real provider credentials/connections). Its request/response wiring is still
        exercised indirectly through the header-injection unit tests in
        `tests/foundry_features_header/`.
      - `list_telephony_calls`/`get_telephony_call`/`transfer_telephony_call`/`end_telephony_call`
        against an actual in-progress or historical call (needs a real inbound telephony call).
      - Reading back a conversation (`project_client.beta.agent_endpoint_conversations.*`) using a
        `conversation_id` produced by a live realtime WebSocket session - the service's REST
        conversation-ID validator rejects the ID format generated by the realtime WS subsystem.
        This is also not practical to cover with HTTP-only recorded tests since it requires an
        actual WebSocket session.
    Once these are fixed/deployed service-side, tests can be added/enabled for them.
    """

    def _make_definition(self, model: str) -> VoiceAgentDefinition:
        return VoiceAgentDefinition(
            model_type="managed",
            model=model,
            instructions="You are a helpful voice assistant.",
            audio=VoiceAgentAudioConfig(
                output=VoiceAgentAudioOutputConfig(voice="en-US-AvaNeural", voice_type="azure-standard")
            ),
            output_modalities=[VoiceOutputModality.AUDIO],
        )

    # To run only this test:
    # pytest tests\agents\test_voice_agent_telephony.py::TestVoiceAgentTelephony::test_telephony_bindings_and_transfer_targets -s
    @pytest.mark.skip(
        reason="Telephony routes are defined in the TypeSpec/SDK but not yet deployed on the live "
        "test service (empty-body 404s at the routing layer). Un-skip once the service deploys them."
    )
    @servicePreparer()
    @recorded_by_proxy()
    def test_telephony_bindings_and_transfer_targets(self, **kwargs):
        """
        Test telephony bindings (list/get/update/delete against a nonexistent binding) and a
        round-trip of the telephony transfer targets configured for a voice agent.

        Routes used in this test:

        Action REST API Route                                                  Client Method
        ------+-------------------------------------------------------------+-----------------------------------------------
        POST   /agents/{agent_name}/versions                                  project_client.agents.create_version()
        GET    /agents/{agent_name}/telephony_bindings                        project_client.agents.list_telephony_bindings()
        GET    /agents/{agent_name}/telephony_transfer_targets                project_client.agents.get_telephony_transfer_targets()
        PUT    /agents/{agent_name}/telephony_transfer_targets                project_client.agents.replace_telephony_transfer_targets()
        GET    /agents/{agent_name}/telephony_bindings/{binding_id}           project_client.agents.get_telephony_binding()
        PATCH  /agents/{agent_name}/telephony_bindings/{binding_id}           project_client.agents.update_telephony_binding()
        DELETE /agents/{agent_name}/telephony_bindings/{binding_id}           project_client.agents.delete_telephony_binding()
        DELETE /agents/{agent_name}                                          project_client.agents.delete()
        """
        print("\n")
        model = kwargs.get("foundry_voice_model_name")
        assert model is not None
        # Voice-agent operations require the preview opt-in.
        project_client = self.create_client(allow_preview=True, **kwargs)
        agent_name = "VoiceAgentTelephonyBindingsTest"

        # Delete any existing agent from previous test runs (ignore failures)
        try:
            project_client.agents.delete(agent_name=agent_name)
        except Exception:  # pylint: disable=broad-except
            pass

        agent_version: AgentVersionDetails = project_client.agents.create_version(
            agent_name=agent_name,
            definition=self._make_definition(model),
        )
        self._validate_agent_version(agent_version, expected_name=agent_name)

        # A freshly created agent has no telephony bindings.
        bindings = list(project_client.agents.list_telephony_bindings(agent_name=agent_name))
        assert len(bindings) == 0

        # A freshly created agent has no telephony transfer targets configured.
        targets: TelephonyTransferTargets = project_client.agents.get_telephony_transfer_targets(agent_name=agent_name)
        assert targets is not None
        assert len(targets.transfer_targets) == 0

        # Configure one PSTN transfer target.
        new_target = TelephonyTransferTarget(
            name="sales_desk",
            description="Transfers to the sales desk for pricing questions.",
            destination=PSTNTelephonyTransferDestination(value="+14255550123"),
        )
        replaced_targets: TelephonyTransferTargets = project_client.agents.replace_telephony_transfer_targets(
            agent_name=agent_name,
            transfer_targets=[new_target],
            etag=None,
            match_condition=MatchConditions.Unconditionally,
        )
        assert len(replaced_targets.transfer_targets) == 1
        assert replaced_targets.transfer_targets[0].name == "sales_desk"
        assert replaced_targets.transfer_targets[0].destination.kind == "pstn"

        # Confirm the change persisted.
        confirmed_targets: TelephonyTransferTargets = project_client.agents.get_telephony_transfer_targets(
            agent_name=agent_name
        )
        assert len(confirmed_targets.transfer_targets) == 1
        assert confirmed_targets.transfer_targets[0].name == "sales_desk"

        # Clear the transfer targets (empty array clears all targets).
        cleared_targets: TelephonyTransferTargets = project_client.agents.replace_telephony_transfer_targets(
            agent_name=agent_name,
            transfer_targets=[],
            etag=None,
            match_condition=MatchConditions.Unconditionally,
        )
        assert len(cleared_targets.transfer_targets) == 0

        # A nonexistent telephony binding returns 404 on get/update/delete.
        fake_binding_id = "nonexistent-binding-id"
        with pytest.raises(ResourceNotFoundError):
            project_client.agents.get_telephony_binding(agent_name=agent_name, binding_id=fake_binding_id)
        with pytest.raises(ResourceNotFoundError):
            project_client.agents.update_telephony_binding(
                agent_name=agent_name,
                binding_id=fake_binding_id,
                body=UpdateTelephonyBindingRequest(status=TelephonyBindingStatus.SUSPENDED),
                etag=None,
                match_condition=MatchConditions.Unconditionally,
            )
        with pytest.raises(ResourceNotFoundError):
            project_client.agents.delete_telephony_binding(
                agent_name=agent_name,
                binding_id=fake_binding_id,
                etag=None,
                match_condition=MatchConditions.Unconditionally,
            )

        # Delete the voice agent.
        result = project_client.agents.delete(agent_name=agent_name)
        assert result.deleted

    # To run only this test:
    # pytest tests\agents\test_voice_agent_telephony.py::TestVoiceAgentTelephony::test_telephony_calls_not_found -s
    @pytest.mark.skip(
        reason="Telephony routes are defined in the TypeSpec/SDK but not yet deployed on the live "
        "test service (empty-body 404s at the routing layer). Un-skip once the service deploys them."
    )
    @servicePreparer()
    @recorded_by_proxy()
    def test_telephony_calls_not_found(self, **kwargs):
        """
        Test telephony calls: listing (empty on a fresh agent) and get/transfer/end against a
        nonexistent call, which return 404.

        Routes used in this test:

        Action REST API Route                                                  Client Method
        ------+-------------------------------------------------------------+-----------------------------------------------
        POST   /agents/{agent_name}/versions                                  project_client.agents.create_version()
        GET    /agents/{agent_name}/telephony_calls                           project_client.agents.list_telephony_calls()
        GET    /agents/{agent_name}/telephony_calls/{call_id}                 project_client.agents.get_telephony_call()
        POST   /agents/{agent_name}/telephony_calls/{call_id}:transfer        project_client.agents.transfer_telephony_call()
        POST   /agents/{agent_name}/telephony_calls/{call_id}:end             project_client.agents.end_telephony_call()
        DELETE /agents/{agent_name}                                          project_client.agents.delete()
        """
        print("\n")
        model = kwargs.get("foundry_voice_model_name")
        assert model is not None
        project_client = self.create_client(allow_preview=True, **kwargs)
        agent_name = "VoiceAgentTelephonyCallsTest"

        # Delete any existing agent from previous test runs (ignore failures)
        try:
            project_client.agents.delete(agent_name=agent_name)
        except Exception:  # pylint: disable=broad-except
            pass

        agent_version: AgentVersionDetails = project_client.agents.create_version(
            agent_name=agent_name,
            definition=self._make_definition(model),
        )
        self._validate_agent_version(agent_version, expected_name=agent_name)

        # A freshly created agent has no telephony call history.
        calls = list(project_client.agents.list_telephony_calls(agent_name=agent_name))
        assert len(calls) == 0

        fake_call_id = "nonexistent-call-id"
        with pytest.raises(ResourceNotFoundError):
            project_client.agents.get_telephony_call(agent_name=agent_name, call_id=fake_call_id)
        with pytest.raises(HttpResponseError) as transfer_exc_info:
            project_client.agents.transfer_telephony_call(
                agent_name=agent_name, call_id=fake_call_id, target="nonexistent-target"
            )
        assert transfer_exc_info.value.status_code == 404
        with pytest.raises(HttpResponseError) as end_exc_info:
            project_client.agents.end_telephony_call(agent_name=agent_name, call_id=fake_call_id)
        assert end_exc_info.value.status_code == 404

        # Delete the voice agent.
        result = project_client.agents.delete(agent_name=agent_name)
        assert result.deleted

    # To run only this test:
    # pytest tests\agents\test_voice_agent_telephony.py::TestVoiceAgentTelephony::test_generated_audio_not_found -s
